#!/usr/bin/env bash
# Tier 1: the known-answer vectors (docs/spec.md part V), as plain text (vectors/known-answers.txt) and as kernel-checked Lean `example`s (VbmRngProofs/Vectors.lean).
# Every line of the text file is translated to one `example ... := by decide +kernel`; VbmRngProofs/Vectors.lean must be exactly that translation (no vector missing, none extra),
# and the translation must elaborate against the library. Negative self-tests: a wrong vector is rejected by the kernel, and a changed text file no longer matches the checked-in Lean file.
# `scripts/test_vectors.sh --emit` prints the translation (that is how VbmRngProofs/Vectors.lean is written). Ends with `ran: vectors: N cases`.
export LC_ALL=C
set -euo pipefail
cd "$(dirname "$0")/.."
VEC=vectors/known-answers.txt
LEANF=VbmRngProofs/Vectors.lean

emit() {  # emit FILE: the Lean module for the vectors of FILE
  cat <<'HEAD'
import VbmRngProofs.Below
import VbmRngProofs.Fraction
import VbmRngProofs.Shuffle
import VbmRngProofs.Bernoulli
import VbmRngProofs.Split
/-! # The known-answer vectors (S9)

Generated by `scripts/test_vectors.sh --emit` from `vectors/known-answers.txt`; do not edit by hand (the gate compares the two). Every vector of docs/spec.md part V is one kernel-checked `example`. -/
namespace VbmRng

HEAD
  awk '
    function join(a, b, sep,   s, i) { s = ""; for (i = a; i <= b; i++) s = s (i > a ? sep : "") $i; return s }
    function upto(a,   i) { for (i = a; i <= NF; i++) if ($i == "=") return i; bad("no =") }
    function at(i) { return "· «at» " i }
    function bad(m) { print "test_vectors: line " NR ": " m ": " $0 > "/dev/stderr"; exit 2 }
    function words(s, e, key,   i, r) { r = ""; for (i = s; i <= e; i++) r = r (i > s ? ", " : "") "(" key ").«at» " (i - s); return "[" r "]" }
    function lst(a, b) { return "[" join(a, b, ", ") "]" }
    function pos(   p) { for (p = 1; p <= NF; p++) if ($p == "@") return p; bad("no @") }
    /^[[:space:]]*(#|$)/ { next }
    {
      k = $1; line = $0; out = ""
      if (k == "mix") out = "mix " $2 " = " $4
      else if (k == "raw") out = words(4, 7, "Stream.ofKey " $2) " = " lst(4, 7)
      else if (k == "seeded") out = "(Stream.ofSeed " $2 ").key = " $4 " ∧ " words(5, 8, "Stream.ofSeed " $2) " = " lst(5, 8)
      else if (k == "at-key") out = "(Stream.ofKey " $2 ").«at» " $3 " = " $5
      else if (k == "at-seed") out = "(Stream.ofSeed " $2 ").«at» " $3 " = " $5
      else if (k == "at-key-advanced") out = "((Stream.ofKey " $2 ").advance " $3 ").«at» " $4 " = " $6
      else if (k == "child") out = "(Stream.ofSeed " $2 ").split " $3 " = Stream.ofKey " $5 " ∧ " words(6, 7, "(Stream.ofSeed " $2 ").split " $3) " = " lst(6, 7)
      else if (k == "child-key") out = "(Stream.ofSeed " $2 ").split " $3 " = Stream.ofKey " $5
      else if (k == "child-key-advanced") out = "((Stream.ofSeed " $2 ").advance " $3 ").split " $4 " = Stream.ofKey " $6
      else if (k == "grandchild") out = "((Stream.ofSeed " $2 ").split " $3 ").split " $4 " = Stream.ofKey " $6
      else if (k == "below") { p = pos(); out = "draws " $2 " " $3 " (Stream.ofSeed " $4 ") = some (" lst(6, p - 1) ", " $(p + 1) ")" }
      else if (k == "below-err") out = "errOf (uniformBelowWith " $2 " " $3 " (Stream.ofSeed " $4 ")) = some ." $6
      else if (k == "fraction") out = "fracVals (uniformFraction " $2 " (Stream.ofSeed " $3 ")) = some (" $5 ", " $2 ", " $7 ")"
      else if (k == "fraction-err") out = "fracErr (uniformFraction " $2 " (Stream.ofSeed " $3 ")) = some ." $5
      else if (k == "shuffle-range") { p = pos(); out = "shuffleVals (shuffle (List.range " $2 ") (Stream.ofSeed " $3 ")) = some (" lst(5, p - 1) ", " $(p + 1) ")" }
      else if (k == "shuffle-nat" || k == "shuffle-chars") {
        e = upto(3); p = pos()
        if (k == "shuffle-chars") { xs = ""; for (i = 3; i < e; i++) xs = xs (i > 3 ? ", " : "") "\047" $i "\047"; ys = ""; for (i = e + 1; i < p; i++) ys = ys (i > e + 1 ? ", " : "") "\047" $i "\047" }
        else { xs = join(3, e - 1, ", "); ys = join(e + 1, p - 1, ", ") }
        out = "shuffleVals (shuffle [" xs "] (Stream.ofSeed " $2 ")) = some ([" ys "], " $(p + 1) ")"
      }
      else if (k == "bernoulli") { p = pos(); out = "bdraws " $2 " (" $3 " : Int) " $4 " (Stream.ofSeed " $5 ") = some (" lst(7, p - 1) ", " $(p + 1) ")" }
      else if (k == "bernoulli-err") out = "bernErr (bernoulli (" $2 " : Int) " $3 " (Stream.ofSeed " $4 ")) = some ." $6
      else bad("unknown kind")
      print "-- " line
      print "example : " out " := by decide +kernel"
    }' "$1" || return 2
  echo
  cat <<'TAIL'
/-- The conformance link: the raw stream of key 0 is the published SplitMix64 generator from state 0. -/
theorem splitmix64_conformance :
    [(Stream.ofKey 0).«at» 0, (Stream.ofKey 0).«at» 1, (Stream.ofKey 0).«at» 2, (Stream.ofKey 0).«at» 3] =
      [0xE220A8397B1DCDAF, 0x6E789E6AA1B965F4, 0x06C45D188009454F, 0xF88BB8A8724C81EC] := by decide +kernel

end VbmRng
TAIL
}

if [ "${1:-}" = "--emit" ]; then emit "$VEC"; exit 0; fi

. ../../.land/tool/lib/ran.sh
fail() { echo "test_vectors: $*" >&2; exit 1; }
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
[ -f "$VEC" ] || fail "$VEC is missing"
nvec=$(awk '!/^[[:space:]]*(#|$)/ { n++ } END { print n + 0 }' "$VEC")
[ "$nvec" -gt 0 ] || fail "$VEC holds no vector"

# 1. The checked-in Lean file is exactly the translation of the text file: no vector is missing, none is extra.
emit "$VEC" > "$T/Vectors.lean"
nex=$(awk '/^example : / { n++ } END { print n + 0 }' "$T/Vectors.lean")
[ "$nex" = "$nvec" ] || fail "$nvec vectors but $nex examples were produced"
diff -u "$LEANF" "$T/Vectors.lean" > "$T/diff" || fail "$LEANF is not the translation of $VEC (run scripts/test_vectors.sh --emit): $(head -c 600 "$T/diff")"
ran_case

# 2. The translation elaborates against the library: every vector holds in the kernel.
lean_check() { lake env lean -DwarningAsError=true "$1"; }
lean_check "$T/Vectors.lean" > "$T/out" 2>&1 || fail "a vector does not hold: $(head -c 1500 "$T/out")"
i=0; while [ "$i" -lt "$nvec" ]; do ran_case; i=$((i + 1)); done

# 3. Negative self-tests: a wrong vector (one digit of the first answer changed) is rejected by the kernel, and a changed text file no longer matches the checked-in Lean file.
awk '!done && !/^[[:space:]]*(#|$)/ { n = length($0); c = substr($0, n, 1); $0 = substr($0, 1, n - 1) (c == "0" ? "1" : "0"); done = 1 } { print }' "$VEC" > "$T/wrong.txt"
cmp -s "$VEC" "$T/wrong.txt" && fail "the self-test did not change a vector"
emit "$T/wrong.txt" > "$T/Wrong.lean"
must_fail "a wrong vector is detected by the kernel" lean_check "$T/Wrong.lean"
case "$MUST_FAIL_ERR" in *"is false"*) ;; *) fail "the wrong vector failed for another reason: $MUST_FAIL_ERR";; esac
must_fail "a changed text file is detected against the checked-in Lean file" diff -u "$LEANF" "$T/Wrong.lean"
printf 'mix 0x01 = 0x02\nbogus 1 = 2\n' > "$T/bad.txt"
must_fail "an unknown vector kind is refused" emit "$T/bad.txt"
ran_done vectors
